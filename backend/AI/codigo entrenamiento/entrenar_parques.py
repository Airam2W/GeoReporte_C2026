import tarfile, urllib.request, re
from pathlib import Path

URL = "http://data.csail.mit.edu/places/places365/train_256_places365standard.tar"
RAW = Path('/content/raw')
pos_set = set(POSITIVAS)
cuenta = {c: 0 for c in POSITIVAS + NEGATIVAS}
limite = lambda c: MAX_POS if c in pos_set else MAX_NEG
patron = re.compile(r'/[a-z]/(.+)/[^/]+\.jpg$')

with urllib.request.urlopen(URL) as resp, tarfile.open(fileobj=resp, mode='r|') as tar:
    for i, m in enumerate(tar):
        if i % 200_000 == 0:
            print(f"{i:,} archivos revisados… actual: {m.name}")
        if not m.isfile():
            continue
        r = patron.search('/' + m.name)
        if not r or r.group(1) not in cuenta:
            continue
        cat = r.group(1)
        if cuenta[cat] >= limite(cat):
            continue
        clase = 'parque' if cat in pos_set else 'no_parque'
        destino = RAW / clase / f"{cat.replace('/', '_')}_{cuenta[cat]:05d}.jpg"
        destino.parent.mkdir(parents=True, exist_ok=True)
        with tar.extractfile(m) as f:
            destino.write_bytes(f.read())
        cuenta[cat] += 1
        if all(cuenta[c] >= limite(c) for c in cuenta):
            print("Todas las categorías completas")
            break

print(cuenta)

import random, shutil
DATA = Path('/content/dataset')
random.seed(42)

for clase in ['parque', 'no_parque']:
    imgs = sorted((RAW / clase).glob('*.jpg'))
    random.shuffle(imgs)
    n_val = int(len(imgs) * 0.15)
    for split, lote in [('val', imgs[:n_val]), ('train', imgs[n_val:])]:
        d = DATA / split / clase
        d.mkdir(parents=True, exist_ok=True)
        for p in lote:
            shutil.move(str(p), d / p.name)
    print(clase, len(imgs), "imágenes")

